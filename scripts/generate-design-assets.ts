/**
 * Generates the per-app design files from the one source, design/tokens.json:
 * tokens.css, the logo SVGs, the favicon SVG and the RenovixLogo component.
 * The apps share no code, so each gets its own generated copy.
 *
 * Usage: bun scripts/generate-design-assets.ts [--check]
 * --check writes nothing and exits 1 when a committed file differs.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

type TypeStyle = {
  size: string;
  weight: number;
  tracking?: string;
  leading: string;
  color?: string;
  mono?: boolean;
  upper?: boolean;
};

type Tokens = {
  palette: Record<string, string>;
  roles: { light: Record<string, string>; dark: Record<string, string> };
  shape: Record<string, string>;
  fonts: { sans: string; mono: string };
  type: Record<string, TypeStyle>;
};

type AppTarget = { name: string; componentPath: string };

const ROOT = join(import.meta.dir, '..');
const TOKENS: Tokens = JSON.parse(readFileSync(join(ROOT, 'design/tokens.json'), 'utf8'));
const APPS: AppTarget[] = [
  { name: 'chat', componentPath: 'src/components/brand/renovix-logo.tsx' },
  { name: 'landing', componentPath: 'src/components/renovix-logo.tsx' },
  { name: 'back-office', componentPath: 'src/components/server/renovix-logo.tsx' },
];
const HEADER = 'Generated by scripts/generate-design-assets.ts from design/tokens.json. Do not edit by hand.';

const color = (name: string): string => {
  const value = TOKENS.palette[name];
  if (!value) throw new Error(`Unknown palette color: ${name}`);
  return value;
};

const roleLines = (roles: Record<string, string>): string =>
  Object.entries(roles)
    .map(([role, name]) => `  --rx-${role}: var(--rx-${name});`)
    .join('\n');

const typeUtility = (name: string, style: TypeStyle): string => {
  const lines = [
    `  font-family: var(--font-${style.mono ? 'mono' : 'sans'});`,
    `  font-size: ${style.size};`,
    `  font-weight: ${style.weight};`,
    `  line-height: ${style.leading};`,
  ];
  if (style.tracking) lines.push(`  letter-spacing: ${style.tracking};`);
  if (style.upper) lines.push('  text-transform: uppercase;');
  if (style.color) lines.push(`  color: var(--rx-${style.color});`);
  return `@utility rx-type-${name} {\n${lines.join('\n')}\n}`;
};

const buildTokensCss = (): string => {
  const palette = Object.entries(TOKENS.palette).map(([name, hex]) => `  --rx-${name}: ${hex};`);
  const shape = Object.entries(TOKENS.shape).map(([name, value]) => `  --rx-${name}: ${value};`);
  const themePalette = Object.keys(TOKENS.palette).map((name) => `  --color-rx-${name}: var(--rx-${name});`);
  const themeRoles = Object.keys(TOKENS.roles.light).map((role) => `  --color-rx-${role}: var(--rx-${role});`);
  return [
    `/* ${HEADER} */`,
    `:root {\n${palette.join('\n')}\n${shape.join('\n')}\n${roleLines(TOKENS.roles.light)}\n}`,
    `/* Dark mode: same roles, no toggle yet. */\n[data-theme='dark'],\n.dark {\n${roleLines(TOKENS.roles.dark)}\n}`,
    `@theme inline {\n  --font-sans: ${TOKENS.fonts.sans};\n  --font-mono: ${TOKENS.fonts.mono};\n${themePalette.join('\n')}\n${themeRoles.join('\n')}\n  --radius-rx: var(--rx-radius);\n  --radius-rx-pill: var(--rx-radius-pill);\n  --shadow-*: initial;\n  --drop-shadow-*: initial;\n}`,
    `@layer base {\n  body {\n    font-family: var(--font-sans);\n    background-color: var(--rx-ground);\n    color: var(--rx-text);\n  }\n}`,
    Object.entries(TOKENS.type).map(([name, style]) => typeUtility(name, style)).join('\n\n'),
  ].join('\n\n') + '\n';
};

const MARK_PATH =
  '<path d="M13 39V9h12a8.5 8.5 0 0 1 0 17h-6M24 26l11 13" fill="none" stroke="{stroke}" stroke-width="{width}" stroke-linecap="round" stroke-linejoin="round"/>';

type MarkOptions = { tile?: string; stroke: string; spark?: string; width?: number };

const buildMarkSvg = ({ tile, stroke, spark, width = 5 }: MarkOptions): string => {
  const parts = [
    tile ? `<rect width="48" height="48" rx="11" fill="${tile}"/>` : '',
    MARK_PATH.replace('{stroke}', stroke).replace('{width}', String(width)),
    spark ? `<circle cx="39" cy="10" r="3" fill="${spark}"/>` : '',
  ].filter(Boolean);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48" role="img" aria-label="Renovix mark">${parts.join('')}</svg>\n`;
};

const buildMarks = (): Record<string, string> => ({
  'public/logo/mark.svg': buildMarkSvg({ tile: color('teal-700'), stroke: color('white'), spark: color('white') }),
  'public/logo/mark-ink.svg': buildMarkSvg({ stroke: color('ink'), spark: color('teal-700') }),
  'public/logo/mark-reversed.svg': buildMarkSvg({ stroke: color('white'), spark: color('white') }),
  'public/logo/mark-favicon.svg': buildMarkSvg({ tile: color('teal-700'), stroke: color('white'), width: 6 }),
  'src/app/icon.svg': buildMarkSvg({ tile: color('teal-700'), stroke: color('white'), width: 6 }),
});

const buildLogoComponent = (): string => `// ${HEADER}
import type { ReactElement } from 'react';

type RenovixLogoLayout = 'mark' | 'horizontal' | 'stacked';
type RenovixLogoTone = 'full' | 'ink' | 'reversed' | 'on-dark';

type RenovixLogoProps = {
  layout?: RenovixLogoLayout;
  tone?: RenovixLogoTone;
  /** Mark size in px: 24 nav, 32 header, 48 avatar. Below 24 the spark is dropped. */
  size?: number;
};

type ToneStyle = { tile: string | null; stroke: string; spark: string; word: string; ai: string };

const TONES: Record<RenovixLogoTone, ToneStyle> = {
  full: { tile: '${color('teal-700')}', stroke: '${color('white')}', spark: '${color('white')}', word: '${color('ink')}', ai: '${color('ink-muted')}' },
  ink: { tile: null, stroke: '${color('ink')}', spark: '${color('teal-700')}', word: '${color('ink')}', ai: '${color('ink-muted')}' },
  reversed: { tile: null, stroke: '${color('white')}', spark: '${color('white')}', word: '${color('white')}', ai: '${color('teal-100')}' },
  'on-dark': { tile: '${color('teal-700')}', stroke: '${color('white')}', spark: '${color('white')}', word: '${color('dark-text')}', ai: '${color('ink-300')}' },
};

const MINIMUM_SPARK_SIZE = 24;
const WORDMARK_RATIO = 0.667;

/** The Renovix open-R mark, optionally with the wordmark (horizontal or stacked lockup). */
export function RenovixLogo({ layout = 'horizontal', tone = 'full', size = 32 }: RenovixLogoProps): ReactElement {
  const style = TONES[tone];
  const hasSpark = size >= MINIMUM_SPARK_SIZE;
  const mark = (
    <svg viewBox="0 0 48 48" width={size} height={size} aria-hidden={layout !== 'mark'} role={layout === 'mark' ? 'img' : undefined} aria-label={layout === 'mark' ? 'Renovix' : undefined}>
      {style.tile ? <rect width="48" height="48" rx="11" fill={style.tile} /> : null}
      <path d="M13 39V9h12a8.5 8.5 0 0 1 0 17h-6M24 26l11 13" fill="none" stroke={style.stroke} strokeWidth={hasSpark ? 5 : 6} strokeLinecap="round" strokeLinejoin="round" />
      {hasSpark ? <circle cx="39" cy="10" r="3" fill={style.spark} /> : null}
    </svg>
  );
  if (layout === 'mark') return mark;
  const wordmark = (
    <span style={{ fontSize: size * WORDMARK_RATIO, fontWeight: 700, letterSpacing: '-0.02em', lineHeight: 1, color: style.word }}>
      Renovix
      <span style={{ fontWeight: 400, marginLeft: '0.22em', color: style.ai }}>AI</span>
    </span>
  );
  const direction = layout === 'stacked' ? 'column' : 'row';
  return (
    <span style={{ display: 'inline-flex', flexDirection: direction, alignItems: 'center', gap: size * 0.25 }}>
      {mark}
      {wordmark}
    </span>
  );
}
`;

const buildFiles = (): Map<string, string> => {
  const files = new Map<string, string>();
  const shared: Record<string, string> = { 'src/app/tokens.css': buildTokensCss(), ...buildMarks() };
  for (const app of APPS) {
    for (const [path, content] of Object.entries(shared)) files.set(`apps/${app.name}/${path}`, content);
    files.set(`apps/${app.name}/${app.componentPath}`, buildLogoComponent());
  }
  return files;
};

const run = (): void => {
  const isCheck = process.argv.includes('--check');
  const stale: string[] = [];
  for (const [path, content] of buildFiles()) {
    const target = join(ROOT, path);
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current === content) continue;
    stale.push(path);
    if (isCheck) continue;
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  if (isCheck && stale.length > 0) {
    console.error(`Out of date (run: bun run design:generate):\n${stale.join('\n')}`);
    process.exit(1);
  }
  console.log(isCheck ? 'design assets up to date' : `wrote ${stale.length} file(s)`);
};

run();
